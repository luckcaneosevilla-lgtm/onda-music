const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('web/online.js','utf8');
const body=source.slice(source.indexOf('function downloadOnline('),source.indexOf('\nwindow.cancelOnlineSearch'));
const calls=[];
const context={offline:{add(items){calls.push(items)}}};
vm.createContext(context);vm.runInContext(body,context);
const track={id:'piped:abcdefghijk',provider:'piped',title:'Canci?n'};
context.downloadOnline(track);
assert.equal(calls.length,1);assert.equal(calls[0][0],track);
context.downloadOnline(null);context.downloadOnline({provider:'local'});
assert.equal(calls.length,1);
assert.ok(!source.includes('download-online'),'Song menu must not offer a competing external download');
assert.ok(!body.includes('navigator.share')&&!body.includes('createElement'),'Download stays inside the app');
console.log('PASS: download controls use the internal offline queue; no external file export');
